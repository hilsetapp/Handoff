import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { ensureHandoffDir, paths } from './config.js';
import { detectPackageManager, detectProjectName } from './detect.js';
import { fingerprint, getGitState } from './git.js';
import { loadNotes } from './notes.js';
import type { Environment, HandoffConfig, Snapshot, TestResult } from './types.js';

export const REPO_URL = 'https://github.com/hilsetapp/handoff';

export function detectEnvironment(cwd: string): Environment {
  return {
    node: process.version,
    pm: detectPackageManager(cwd),
    os: process.platform,
  };
}

/** Run the test command, capturing exit code and the tail of the output. */
export function runTests(command: string, cwd: string, timeoutMs = 300_000): TestResult {
  const started = new Date();
  const res = spawnSync(command, {
    cwd,
    shell: true,
    encoding: 'utf8',
    timeout: timeoutMs,
    maxBuffer: 16 * 1024 * 1024,
    env: { ...process.env, CI: 'true' },
  });
  const combined = `${res.stdout ?? ''}\n${res.stderr ?? ''}`.trim();
  const lines = combined.split('\n').filter((l) => l.trim());
  const tail = lines.slice(-10).join('\n').trim() || undefined;
  return {
    command,
    ok: res.status === 0,
    exitCode: res.status ?? null,
    ranAt: started.toISOString(),
    tail,
  };
}

/** Collect a full snapshot of the current working state. */
export function takeSnapshot(
  cwd: string,
  config: HandoffConfig,
  opts: { summary?: string; runTests: boolean; version: string },
): Snapshot {
  const git = getGitState(cwd, config.recentCommits);
  const snap: Snapshot = {
    tool: `handoff ${opts.version} (${REPO_URL})`,
    generatedAt: new Date().toISOString(),
    project: detectProjectName(cwd),
    summary: opts.summary,
    git,
    tests:
      opts.runTests && config.testCommand ? runTests(config.testCommand, cwd) : null,
    notes: loadNotes(cwd),
    env: detectEnvironment(cwd),
    fingerprint: fingerprint(git),
  };
  return snap;
}

function dateOnly(iso: string): string {
  return iso.slice(0, 10);
}

/**
 * Render a snapshot as the portable markdown context file.
 * Pure function — unit tested. This format is the product:
 * stable, greppable, and readable by both humans and agents.
 */
export function buildMarkdown(snap: Snapshot): string {
  const L: string[] = [];

  L.push(`# Session handoff — ${snap.project}`);
  L.push('');
  L.push(`> Generated by ${snap.tool} · ${snap.generatedAt}`);
  L.push('>');
  L.push('> **AI coding agents:** read this file at session start, before touching code.');
  L.push('> It holds the live working state that your static instructions don\'t:');
  L.push('> open next steps, decisions, failed approaches and test status.');
  L.push('');
  if (snap.summary) {
    L.push(`**Focus:** ${snap.summary}`);
    L.push('');
  }

  // --- Next steps -------------------------------------------------------
  L.push('## Next steps');
  L.push('');
  if (snap.notes.next.length === 0) {
    L.push('_None recorded. Add one with `handoff next "..."`._');
  } else {
    for (const n of snap.notes.next) {
      L.push(`- [${n.done ? 'x' : ' '}] ${n.text} _(added ${dateOnly(n.ts)})_`);
    }
  }
  L.push('');

  // --- Decisions --------------------------------------------------------
  L.push('## Decisions made');
  L.push('');
  if (snap.notes.decisions.length === 0) {
    L.push('_None recorded._');
  } else {
    for (const n of snap.notes.decisions) L.push(`- **${dateOnly(n.ts)}** — ${n.text}`);
  }
  L.push('');

  // --- Failed approaches --------------------------------------------------
  L.push('## Failed approaches (do not retry)');
  L.push('');
  if (snap.notes.failed.length === 0) {
    L.push('_None recorded._');
  } else {
    for (const n of snap.notes.failed) L.push(`- **${dateOnly(n.ts)}** — ${n.text}`);
  }
  L.push('');

  // --- Blockers -----------------------------------------------------------
  if (snap.notes.blockers.length > 0) {
    L.push('## Blockers');
    L.push('');
    for (const n of snap.notes.blockers) L.push(`- ${n.text}`);
    L.push('');
  }

  // --- Working tree -------------------------------------------------------
  L.push('## Working tree');
  L.push('');
  if (!snap.git.isRepo) {
    L.push('_Not a git repository._');
  } else {
    const where = snap.git.branch ? `branch \`${snap.git.branch}\`` : 'detached HEAD';
    let line = `- ${where} · HEAD \`${snap.git.commit ?? 'unknown'}\``;
    if (snap.git.upstream) {
      line += ` · upstream \`${snap.git.upstream}\` (ahead ${snap.git.ahead ?? 0}, behind ${snap.git.behind ?? 0})`;
    }
    L.push(line);
    if (snap.git.recentCommits.length > 0) {
      L.push('- Recent commits:');
      for (const c of snap.git.recentCommits) L.push(`  - \`${c.hash}\` ${c.subject}`);
    }
    if (snap.git.changes.length === 0) {
      L.push('- Working tree clean');
    } else {
      L.push(`- Uncommitted changes (${snap.git.changes.length})${snap.git.shortstat ? `: ${snap.git.shortstat.trim()}` : ''}`);
      for (const ch of snap.git.changes) {
        L.push(`  - ${ch.staged ? '[staged] ' : ''}${ch.status} \`${ch.path}\``);
      }
    }
  }
  L.push('');

  // --- Tests ---------------------------------------------------------------
  L.push('## Tests');
  L.push('');
  if (snap.tests) {
    L.push(`- \`${snap.tests.command}\` — ${snap.tests.ok ? '✅ PASS' : '❌ FAIL'} (exit ${snap.tests.exitCode ?? 'timeout'}) · ${snap.tests.ranAt}`);
    if (snap.tests.tail) {
      L.push('');
      L.push('<details><summary>output tail</summary>');
      L.push('');
      L.push('```');
      L.push(snap.tests.tail);
      L.push('```');
      L.push('</details>');
    }
  } else {
    L.push('_Not run. Configure `"testCommand"` in `.handoff/config.json` and save again._');
  }
  L.push('');

  // --- Environment ---------------------------------------------------------
  L.push('## Environment');
  L.push('');
  L.push(`- Node ${snap.env.node}${snap.env.pm ? ` · ${snap.env.pm}` : ''} · ${snap.env.os}`);
  L.push('');

  return L.join('\n');
}

/** Write the snapshot to .handoff/HANDOFF.md (+ JSON sidecar). Returns the md path. */
export function writeSnapshot(cwd: string, snap: Snapshot): string {
  ensureHandoffDir(cwd);
  const p = paths(cwd);
  writeFileSync(p.md, buildMarkdown(snap), 'utf8');
  writeFileSync(p.state, JSON.stringify(snap, null, 2) + '\n', 'utf8');
  return p.md;
}
